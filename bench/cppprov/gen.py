#!/usr/bin/env python3
"""gen.py OUTDIR R N [N...] : configs of the stub-model comparison (ww-1df.42). Stdlib only, deterministic. Per N (default 100, 1250), under OUTDIR/N<n>_R<R>/:
  scada.json      R RTUs `rtu-1..R`, N breaker points brk-0000.active .. dealt round-robin over them (coil = di = index within the RTU), no generators; what ffcontrol drives
  model.yaml      ferrofire's equally trivial model: N binary inputs brk-NNNN.active (default true) republished by an output of the same name, no power block
                  (a write sets the input, the next tick publishes it: the stub's echo); one publish slice per RTU on its own group 239.0.1.<r>; publish_rate is patched in by run.py (__RATE__)
  rtu-<r>-<group>.xml  the field-device config (the SAME file for stock bennu-field-deviced and ferrofire field-device): input stream group 239.0.0.1 (C++ provider, one group
                  for everything, like stock pybennu) or 239.0.1.<r> (ferrofire provider, its per-RTU slices), output to tcp://provider:5555; the shape of bench/gen_grid.py's fd_xml."""
import json, os, sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import gen_grid

STEP = 0.05   # the stub's fixed step and ferrofire's `dt`


def main(out, r, ns):
    for n in ns:
        d = f"{out}/N{n}_R{r}"
        maps = [{"name": f"rtu-{k + 1}", "gens": [], "aux": [], "breakers": [{"idx": i, "point": f"brk-{i:04d}.active", "coil": j, "di": j} for j, i in enumerate(range(k, n, r))]} for k in range(r)]
        gen_grid.write(f"{d}/scada.json", json.dumps({"R": r, "port": 502, "rtus": [m | {"host": m["name"]} for m in maps], "flip_order": list(range(n)), "gen_order": [], "gen_setpoint": 40.0}, indent=1))
        for k, m in enumerate(maps):
            for grp in ("239.0.0.1", f"239.0.1.{k + 1}"):
                gen_grid.write(f"{d}/{m['name']}-{grp}.xml", gen_grid.fd_xml(m, f"udp://*;{grp}:40000", "tcp://provider:5555", "tcp://0.0.0.0:502"))
        ins = "".join(f"  brk-{i:04d}.active: {{type: binary, default: true}}\n" for i in range(n))
        outs = "".join(f"  brk-{i:04d}.active: {{type: binary}}\n" for i in range(n))
        sl = "".join(f"  - endpoint: 'udp://*;239.0.1.{k + 1}:40000'\n    tags: [{', '.join(b['point'] for b in m['breakers'])}]\n" for k, m in enumerate(maps))
        gen_grid.write(f"{d}/model.yaml", f"# generated by bench/cppprov/gen.py: do not edit\nversion: 1\ndt: {STEP}\npublish_rate: __RATE__\ninputs:\n{ins}outputs:\n{outs}publish_slices:\n{sl}")
        print(f"N{n} R{r}: {n} breaker points over {r} RTUs -> {d}")


if __name__ == "__main__":
    main(sys.argv[1], int(sys.argv[2]), [int(x) for x in sys.argv[3:]] or [100, 1250])
