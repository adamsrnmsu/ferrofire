from dnp3probe import *
# ww-a12: output points (g10/g40) after ASSIGN_CLASS, and reads of the output groups at variations ferrofire once refused.
# Run against diff-server.xml: binary outputs 4 (sbo) and 5, analog outputs 3 (sbo) and 8.
import dnp3probe as P
print("== start")
req("integrity", 1, INTEG); confirm("confirm integrity", 0)
print("== reads of the output groups by variation")
for v in range(0, 5):
    req("g10v%d" % v, 1, hdr(10, v, 6))
for v in range(0, 12):
    req("g40v%d" % v, 1, hdr(40, v, 6))
for g, v in [(11, 0), (11, 1), (11, 2), (11, 3), (13, 0), (13, 1), (13, 2), (13, 3), (13, 4), (13, 5), (12, 1), (12, 2), (41, 1), (41, 5), (42, 9), (42, 10)]:
    req("g%dv%d" % (g, v), 1, hdr(g, v, 6))
req("g10v3 range 4-5", 1, hdr(10, 3, 0, 4, 5))
req("g40v5 range 3-8", 1, hdr(40, 5, 0, 3, 8))
req("g10v2 + g10v3", 1, hdr(10, 2, 6) + hdr(10, 3, 6))
print("== assign class on the output groups")
req("assign g10 4-5 class1", 22, bytes([60, 2, 6, 10, 0, 0, 4, 5]))
req("assign g40 3-8 class2", 22, bytes([60, 3, 6, 40, 0, 0, 3, 8]))
req("assign g10 bad range", 22, bytes([60, 2, 6, 10, 0, 0, 4, 9]))
req("class1 after assign", 1, bytes([60, 2, 6]))
req("class0 after assign", 1, bytes([60, 1, 6]))
print("== output changes")
req("direct crob 5 latch-on", 5, CROB(5, 3))
req("class1 after crob", 1, bytes([60, 2, 6]))
confirm("confirm crob event")
req("class1 after confirm", 1, bytes([60, 2, 6]))
req("direct crob 5 latch-on again (no change)", 5, CROB(5, 3))
req("class1 no change", 1, bytes([60, 2, 6]))
req("direct crob 5 latch-off", 5, CROB(5, 4))
req("g2v0 after crob (not an input)", 1, hdr(2, 0, 6))
req("g11v0 after crob", 1, hdr(11, 0, 6)); confirm("confirm g11v0")
for g, v, code in [(11, 1, 3), (11, 2, 4), (11, 3, 3), (11, 0, 4), (11, 2, 3)]:
    req("direct crob 5 code %d" % code, 5, CROB(5, code))
    req("g%dv%d events" % (g, v), 1, hdr(g, v, 6)); confirm("confirm g%dv%d" % (g, v))
req("g42v0 empty", 1, hdr(42, 0, 6))
req("direct aof 8", 5, AOF(8, 1.5))
req("class2 after aof", 1, bytes([60, 3, 6])); confirm("confirm aof event")
req("direct aof 8 2.5", 5, AOF(8, 2.5))
for v in range(0, 9):
    req("g42v%d events" % v, 1, hdr(42, v, 6)); confirm("confirm g42v%d" % v)
    req("direct aof 8 %d.5" % (v + 3), 5, AOF(8, v + 3.5))
req("g32v0 not an input event", 1, hdr(32, 0, 6))
req("g13v0..2", 1, hdr(13, 0, 6) + hdr(13, 1, 6))
req("class123 after changes", 1, CLS); confirm("confirm changes")
req("direct crob 5 latch-off", 5, CROB(5, 4))
req("direct aof 8 7", 5, AOF(8, 7))
req("class0 events pending", 1, bytes([60, 1, 6]))
req("integrity events pending", 1, INTEG); confirm("confirm integrity")
req("class123 after integrity", 1, CLS)
print("== assigned back to class 0")
req("assign g10 4-5 class0", 22, bytes([60, 1, 6, 10, 0, 0, 4, 5]))
req("direct crob 5 latch-on", 5, CROB(5, 3))
req("class1 after class0 assign", 1, bytes([60, 2, 6]))
print("== several refused headers in one READ")
for a, b in [((13, 1), (13, 0)), ((13, 1), (12, 1)), ((13, 1), (1, 2)), ((1, 2), (13, 1)), ((13, 0), (1, 2)), ((10, 1), (40, 5)), ((40, 5), (10, 1)), ((13, 1), (60, 2))]:
    req("g%dv%d + g%dv%d" % (a + b), 1, hdr(a[0], a[1], 6) + hdr(b[0], b[1], 6))
print("== a control reaches the output status at once, after its own response")
req("assign g10 4-5 class1", 22, bytes([60, 2, 6, 10, 0, 0, 4, 5]))
req("assign g40 3-8 class2", 22, bytes([60, 3, 6, 40, 0, 0, 3, 8]))
req("drain", 1, CLS); confirm("confirm drain")
for i in range(3):
    req("crob on", 5, CROB(5, 3), wait=0.02)
    req("g10 20 ms later", 1, hdr(10, 0, 6), wait=0.02)
    req("class1 20 ms later", 1, bytes([60, 2, 6]), wait=0.02)
    confirm("confirm")
    req("aof", 5, AOF(8, i + 0.5), wait=0.02)
    req("g40 20 ms later", 1, hdr(40, 1, 6), wait=0.02)
    req("class2 20 ms later", 1, bytes([60, 3, 6]), wait=0.02)
    confirm("confirm")
    req("crob off", 5, CROB(5, 4), wait=0.02)
    req("class1 20 ms later", 1, bytes([60, 2, 6]), wait=0.02)
    confirm("confirm")
