from dnp3probe import *
# ww-ke0: the config keys class, sgvar, egvar, deadband and event-buffer-size, and the four point tables (diff-cfg-server.xml).
# A name opendnp3 does not know leaves the point out without a word (bi5-8, 12-14, bo12, ai7-9, ao22); outputs take class only; an input and
# an output share index 10 (binary) and 20 (analog). Run against stock v2026.11.03, the transcript is the truth.
print("== start: the Size lines are in the log; integrity shows each point's static variation and its start-up event")
req("integrity", 1, INTEG); confirm("confirm integrity")
print("== static reads: each point answers in its own variation, a named variation is asked for")
for g in (1, 10, 30, 40):
    req("g%dv0" % g, 1, hdr(g, 0, 6))
for g, v in [(1, 1), (1, 2), (30, 1), (30, 2), (30, 3), (30, 4), (30, 5), (30, 6), (10, 2), (40, 1), (40, 2), (40, 3), (40, 4)]:
    req("g%dv%d" % (g, v), 1, hdr(g, v, 6))
req("g1v0 10-11", 1, hdr(1, 0, 0, 10, 11)); req("g10v0 10-11", 1, hdr(10, 0, 0, 10, 11))
req("g30v0 20-21", 1, hdr(30, 0, 0, 20, 21)); req("g40v0 20-21", 1, hdr(40, 0, 0, 20, 21))
print("== events by class; the variation is the point's egvar, or the one the master names")
def pub(body): publish(body)
pub("pbi0:true,pbi1:true,pbi2:true,pbi3:true,pbi4:true,pbi9:true,pbi10:true,pbi11:true,pai0:3,pai1:3,pai2:3,pai3:3,pai4:3,pai5:3,pai6:3,pai20:3,pai21:3")
req("class1", 1, bytes([60, 2, 6])); confirm("confirm class1")
req("class2", 1, bytes([60, 3, 6])); confirm("confirm class2")
req("class3", 1, bytes([60, 4, 6])); confirm("confirm class3")
req("class0 only", 1, bytes([60, 1, 6]))
print("== deadband: the value of the last event is the reference, a change of more than the deadband is an event")
for v in (6, 11, 11, 16, 16.5, 10, 0, -0.5, 8.5):
    pub("pai0:%s,pai1:%s,pai2:%s,pai3:%s,pai21:%s" % ((v,) * 5))
    req("ai = %s" % v, 1, CLS); confirm("confirm")
print("== a class 0 point is not reported, but its deadband reference moves; assigned a class it reports from there")
req("assign g30 21 class1", 22, bytes([60, 2, 6, 30, 0, 0, 21, 21]))
for v in (9, 14, 15):
    pub("pai21:%s" % v)
    req("ai21 = %s" % v, 1, CLS); confirm("confirm")
print("== a named event variation overrides the point's own, variation 0 keeps it")
pub("pai0:100,pai1:100,pai2:100,pai3:100,pai4:100,pai5:100,pai6:100,pbi0:false,pbi1:false,pbi11:false")
req("g32v2", 1, hdr(32, 2, 6)); confirm("confirm g32v2")
pub("pai0:200,pai3:200,pbi0:true,pbi1:true,pbi11:true")
req("g2v3", 1, hdr(2, 3, 6)); confirm("confirm g2v3")
req("g32v0", 1, hdr(32, 0, 6)); confirm("confirm g32v0")
pub("pai0:300,pai5:300,pbi0:false,pbi1:false,pbi11:false")
req("g32v0 + g2v0", 1, hdr(32, 0, 6) + hdr(2, 0, 6)); confirm("confirm")
print("== outputs: class from the config, events in g11 and g42, and an input at the same index is a point of its own")
for i, (code, v) in enumerate([(3, 1.5), (4, 2.5), (3, 3.5)]):
    req("crob 10 code %d" % code, 5, CROB(10, code)); req("g10 10-11", 1, hdr(10, 0, 0, 10, 11)); req("g1 10-11", 1, hdr(1, 0, 0, 10, 11))
    req("aof 20 %s" % v, 5, AOF(20, v)); req("g40 20-21", 1, hdr(40, 0, 0, 20, 21)); req("g30 20-21", 1, hdr(30, 0, 0, 20, 21))
    req("class123", 1, CLS); confirm("confirm")
req("crob 11 direct (sbo)", 5, CROB(11, 3))
req("crob 13 direct", 5, CROB(13, 3)); req("crob 12 (left out)", 5, CROB(12, 3)); req("crob 9 (an input)", 5, CROB(9, 3))
req("aof 21", 5, AOF(21, 4)); req("aof 22 (left out)", 5, AOF(22, 4)); req("aof 9 (an input)", 5, AOF(9, 4))
req("class123", 1, CLS); confirm("confirm")
print("== ASSIGN_CLASS reaches one table: g1 index 10 and g10 index 10")
req("assign g1 10 class3", 22, bytes([60, 4, 6, 1, 0, 0, 10, 10]))
req("assign g10 10 class0", 22, bytes([60, 1, 6, 10, 0, 0, 10, 10]))
pub("pbi10:false")
req("crob 10 on", 5, CROB(10, 3))
req("class123", 1, CLS); confirm("confirm")
print("== a full event buffer (10 per type): the oldest events go and IIN2.3 is set")
for i in range(12):
    pub("pai20:%d" % (50 + i))
req("class1 after 12 events", 1, bytes([60, 2, 6])); confirm("confirm")
req("class1 again", 1, bytes([60, 2, 6])); confirm("confirm")
req("assign g40 20 class1", 22, bytes([60, 2, 6, 40, 0, 0, 20, 20]))
req("assign g10 10 class1", 22, bytes([60, 2, 6, 10, 0, 0, 10, 10]))
for i in range(12):
    req("crob 10 %d" % i, 5, CROB(10, 3 + i % 2), wait=0.1)
    req("aof 20 %d" % i, 5, AOF(20, 60 + i), wait=0.1)
req("g10", 1, hdr(10, 0, 0, 10, 11))
req("class1 after 12 output events", 1, bytes([60, 2, 6])); confirm("confirm")
req("class1 again", 1, bytes([60, 2, 6])); confirm("confirm")
