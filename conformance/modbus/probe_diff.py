"""The SPEC 4.1 transcript (the 24 rows of conformance/stock/probe_modbus.py) against the stock sample config, provider down, then a
sweep of every function code and the MBAP-level edge cases that stay inside what stock survives (no frame over 1018 bytes: Q9)."""
from modbusprobe import *

publish("load-1_bus-1.mw:250.5,generator-1_bus-1.active:true,load-1_bus-1.active:false,bus-1.gen_mw:12.5")
print("== reads before any write (stock applies a queued write ~15 s after the provider stops answering: nothing below may read 30000/40000 late)")
for tid in (0, 0x1234, 0xFFFF): rd("FC4 tid=%04x" % tid, 4, 30000, 1, tid=tid)
x("FC23 tid=1234", 23, bytes(9), tid=0x1234)
x("FC43 tid=1234", 43, b"\x0e\x01\x00", tid=0x1234)
x("FC23 uid=9", 23, bytes(9), uid=9)
x("FC3 + 4 extra bytes", 3, struct.pack(">HH", 40000, 1) + b"\1\2\3\4")
x("FC4 + 245 extra bytes (length 254)", 4, struct.pack(">HH", 30000, 1) + bytes(245))
s = Sess()
s.send("pipelined FC4+FC3", mbap(1, 4, struct.pack(">HH", 30000, 1), tid=1) + mbap(1, 3, struct.pack(">HH", 40000, 1), tid=2))
s.send("then a single FC4", mbap(1, 4, struct.pack(">HH", 30000, 1), tid=3))
s.close()
print("== SPEC 4.1 rows")
rd("FC4 30000 x1", 4, 30000, 1)
rd("FC4 30000 x2 (gap)", 4, 30000, 2)
rd("FC4 29999 x1", 4, 29999, 1)
rd("FC2 10000 x2", 2, 10000, 2)
rd("FC2 10000 x3 (gap)", 2, 10000, 3)
rd("FC1 coil 0 x2", 1, 0, 2)
rd("FC1 coil 5 (none)", 1, 5, 1)
rd("FC3 40000 x1", 3, 40000, 1)
rd("FC3 40001 (none)", 3, 40001, 1)
rd("FC4 uid=7", 4, 30000, 1, uid=7)
rd("FC4 uid=0", 4, 30000, 1, uid=0)
rd("FC4 uid=255", 4, 30000, 1, uid=255)
wr("FC5 coil0 ON", 5, 0, 0xFF00)
wr("FC5 coil9 (none)", 5, 9, 0xFF00)
wr("FC5 coil0 val 1234", 5, 0, 1234)
wr("FC6 40000=32768", 6, 40000, 32768)
wm("FC16 40000 x1", 16, 40000, 1, struct.pack(">H", 65535))
wm("FC15 coils 0..1", 15, 0, 2, bytes([3]))
x("FC23 unsupported", 23, bytes(9))
x("FC8 diag", 8, bytes(4))
x("FC43 devid", 43, b"\x0e\x01\x00")
rd("FC4 x0 qty", 4, 30000, 0)
rd("FC4 x126 qty", 4, 30000, 126)
rd("FC3 after write", 3, 40000, 1)
rd("FC1 after FC5", 1, 0, 2)
print("== every function code, request body 0000 0001")
for fc in range(256):
    if fc in (1, 2, 3, 4, 5, 6, 15, 16): continue
    x("FC%d" % fc, fc, bytes([0, 0, 0, 1]))
print("== a body shorter than four bytes (every function code reads addr+qty first): exception code 4 under function byte 0x80")
for fc in (1, 2, 3, 4, 5, 6, 7, 15, 16, 23, 43, 255):
    for n in range(4): x("FC%d body %d bytes" % (fc, n), fc, bytes(n))
x("FC43 0e 01 00", 43, b"\x0e\x01\x00")
x("FC43 0e 01 00 00 00", 43, b"\x0e\x01\x00\x00\x00")
print("== longer than needed: FC5/FC6 echo the whole request, FC15/16 answer from the header (FC1-4 ignore the rest: read before the first write, above)")
x("FC5 + 2 extra bytes", 5, struct.pack(">HH", 0, 0xFF00) + b"\1\2")
x("FC6 + 2 extra bytes", 6, struct.pack(">HH", 40000, 5) + b"\1\2")
x("FC16 x1 + 2 extra data bytes", 16, struct.pack(">HHB", 40000, 1, 2) + b"\0\5\1\2")
print("== quantity limits and check order")
rd("FC1 x0", 1, 0, 0); rd("FC1 x1", 1, 0, 1); rd("FC1 x2000 @0", 1, 0, 2000); rd("FC1 x2001 @0", 1, 0, 2001)
rd("FC2 x2000 @10000", 2, 10000, 2000); rd("FC2 x2001 @10000", 2, 10000, 2001); rd("FC2 x0 @10000", 2, 10000, 0)
rd("FC2 x2001 @unmapped", 2, 500, 2001); rd("FC2 x1 @unmapped", 2, 500, 1)
rd("FC3 x0", 3, 40000, 0); rd("FC3 x125 @40000", 3, 40000, 125); rd("FC3 x126 @40000", 3, 40000, 126)
rd("FC3 x126 @unmapped", 3, 100, 126); rd("FC3 x1 @unmapped", 3, 100, 1)
rd("FC4 x125 @30000", 4, 30000, 125); rd("FC4 x126 @unmapped", 4, 100, 126)
rd("FC4 @65535 x1", 4, 65535, 1); rd("FC4 @65535 x2", 4, 65535, 2); rd("FC1 @65535 x2", 1, 65535, 2)
print("== writes: limits and byte counts (provider down: nothing lands)")
wm("FC15 x0", 15, 0, 0, b"")
wm("FC15 x1", 15, 0, 1, bytes([1]))
wm("FC15 x1 bytecount 2", 15, 0, 1, bytes([1, 0]))
wm("FC15 x9 bytecount 1", 15, 0, 9, bytes([1]))
wm("FC15 x1968 (unmapped)", 15, 0, 1968, bytes(246))
wm("FC15 x1969 bc 247 (unmapped; no qty limit)", 15, 0, 1969, bytes(247))
wm("FC15 x1976 bc 247 (length 254)", 15, 0, 1976, bytes(247))
wm("FC15 x1977 bc 247", 15, 0, 1977, bytes(247))
wm("FC15 unmapped first", 15, 7, 1, bytes([1]))
wm("FC15 last unmapped", 15, 1, 2, bytes([3]))
wm("FC16 x0", 16, 40000, 0, b"")
wm("FC16 x1", 16, 40000, 1, bytes(2))
wm("FC16 x1 bytecount 4", 16, 40000, 1, bytes(4))
wm("FC16 x2 bytecount 2", 16, 40000, 2, bytes(2))
wm("FC16 x2 (last unmapped)", 16, 40000, 2, bytes(4))
wm("FC16 x123 (length 253)", 16, 40000, 123, bytes(246))
wm("FC16 unmapped", 16, 40001, 1, bytes(2))
wr("FC6 unmapped", 6, 40001, 1)
wr("FC5 0x0000", 5, 0, 0)
wr("FC5 0xff00 @unmapped", 5, 4, 0xFF00)
wr("FC5 0x00ff", 5, 0, 0x00FF)
wr("FC5 0xffff", 5, 1, 0xFFFF)
